/**
 * The fence - the fold's own image must prove itself before the word
 * rides. A fold that cannot prove itself prices nothing (the fence
 * law: the word never rides a lie). The zero count is lawful (the
 * batch's own zero rides - the field's own face 352 the proof).
 *
 * @param {object|null} [e] the trend fold:
 *   { back: {batches}, prev: {batches}, cur: {batches} }
 * @returns {boolean}
 */
export function batchTrendConsistent (e) {
  if (!e || typeof e !== 'object' || Array.isArray(e)) return false
  const faceOk = (s) => {
    if (!s || typeof s !== 'object' || Array.isArray(s)) return false
    return Number.isInteger(s.batches) && s.batches >= 0
  }
  return faceOk(e.back) && faceOk(e.prev) && faceOk(e.cur)
}

